// Helper function to get a random response
export const getRandomResponse = (responseArray) => {
  return responseArray[Math.floor(Math.random() * responseArray.length)];
};

// Main conversational response function
export const getConversationalResponse = (question, language = 'english') => {
  const q = question.toLowerCase().trim();
  const keywords = conversationalData.keywords;
  const responses = conversationalData.responses;
  const lang = language === 'sesotho' ? 'sesotho' : 'english';

  // Check in priority order
  const checks = [
    { key: 'greeting', responseKey: 'greeting' },
    { key: 'howAreYou', responseKey: 'howAreYou' },
    { key: 'thanks', responseKey: 'thanks' },
    { key: 'bye', responseKey: 'bye' },
    { key: 'whoAreYou', responseKey: 'whoAreYou' },
    { key: 'whatCanYouDo', responseKey: 'whatCanYouDo' },
    { key: 'help', responseKey: 'help' },
    { key: 'motivation', responseKey: 'motivation' },
    { key: 'aboutLeSAH', responseKey: 'aboutLeSAH' },
    { key: 'moneyBasics', responseKey: 'moneyBasics' },
    { key: 'advice', responseKey: 'advice' },
    { key: 'confused', responseKey: 'confused' },
    { key: 'wrongAnswer', responseKey: 'wrongAnswer' },
    { key: 'celebration', responseKey: 'celebration' },
  ];

  for (const check of checks) {
    if (keywords[check.key]?.some((kw) => q.includes(kw.toLowerCase()))) {
      const responseArray = responses[check.responseKey]?.[lang] || responses[check.responseKey]?.english;
      if (responseArray && responseArray.length > 0) {
        return getRandomResponse(responseArray);
      }
    }
  }

  // Fallback
  const fallbackArray = responses.fallback?.[lang] || responses.fallback?.english;
  return fallbackArray ? getRandomResponse(fallbackArray) : null;
};