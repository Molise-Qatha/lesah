// Helper function to get a random response
export const getRandomResponse = (responseArray) => {
  return responseArray[Math.floor(Math.random() * responseArray.length)];
};

// Main conversational response function
export const getConversationalResponse = (question, language = 'english') => {
  const q = question.toLowerCase().trim();
  const keywords = conversationalData.keywords;
  const responses = conversationalData.responses;

  // Check greetings
  if (keywords.greeting_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.greeting[language] || responses.greeting.english);
  }

  // Check "how are you"
  if (keywords.howAreYou_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.howAreYou[language] || responses.howAreYou.english);
  }

  // Check thanks
  if (keywords.thanks_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.thanks[language] || responses.thanks.english);
  }

  // Check goodbye
  if (keywords.bye_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.bye[language] || responses.bye.english);
  }

  // Check "who are you"
  if (keywords.whoAreYou_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.whoAreYou[language] || responses.whoAreYou.english);
  }

  // Check "what can you do"
  if (keywords.whatCanYouDo_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.whatCanYouDo[language] || responses.whatCanYouDo.english);
  }

  // Check help
  if (keywords.help_en.some((kw) => q.includes(kw))) {
    return getRandomResponse(responses.help[language] || responses.help.english);
  }

  // Fallback
  return null;
};